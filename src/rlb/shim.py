"""PATH shims that time every Rocq binary the agent runs.

Each shim execs the real binary and appends one TSV line to $RLB_TRACE:
    bin  start_epoch  end_epoch  exit_code  base64(NUL-joined argv)
Nested invocations (e.g. `rocq compile` exec'ing `coqc`) are not double
counted: the outer shim sets RLB_IN_PROVER and inner shims just exec.
"""
from __future__ import annotations

import base64
import os
import stat
from dataclasses import dataclass
from pathlib import Path

SHIMMED = [
    "coqc", "coqtop", "coqchk", "coqdep", "coqnative", "coq_makefile", "coqdoc", "coqidetop",
    "coq-lsp", "rocq", "rocqchk", "rocqnative", "rocqdep", "pet", "pet-server", "fcc",
]

_SCRIPT = """#!/usr/bin/env bash
# rlb timing shim (generated by rlb/shim.py)
real="$RLB_REAL_BIN/{name}"
if [ -z "${{RLB_TRACE:-}}" ] || [ -n "${{RLB_IN_PROVER:-}}" ]; then exec "$real" "$@"; fi
export RLB_IN_PROVER=1
argv=$(printf '%s\\0' "$@" | base64 -w0)
t0=$EPOCHREALTIME
"$real" "$@"
rc=$?
t1=$EPOCHREALTIME
printf '%s\\t%s\\t%s\\t%s\\t%s\\n' "{name}" "$t0" "$t1" "$rc" "$argv" >> "$RLB_TRACE"
exit $rc
"""


def make_shim_dir(shim_dir: Path, real_bin: Path) -> Path:
    shim_dir.mkdir(parents=True, exist_ok=True)
    for name in SHIMMED:
        if not (real_bin / name).exists():
            continue
        p = shim_dir / name
        p.write_text(_SCRIPT.format(name=name))
        p.chmod(p.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return shim_dir


def shim_env(shim_dir: Path, real_bin: Path, trace: Path, base: dict[str, str]) -> dict[str, str]:
    env = dict(base)
    env["PATH"] = f"{shim_dir}{os.pathsep}{env.get('PATH', '')}"
    env["RLB_REAL_BIN"] = str(real_bin)
    env["RLB_TRACE"] = str(trace)
    env.pop("RLB_IN_PROVER", None)
    return env


@dataclass(frozen=True)
class ProverCall:
    bin: str
    start: float
    end: float
    rc: int
    argv: tuple[str, ...]

    @property
    def seconds(self) -> float:
        return self.end - self.start


def parse_trace(trace: Path) -> list[ProverCall]:
    if not trace.exists():
        return []
    calls = []
    for line in trace.read_text().splitlines():
        parts = line.split("\t")
        if len(parts) != 5:
            continue  # truncated line (harness killed mid-write)
        b, t0, t1, rc, argv = parts
        args = base64.b64decode(argv).split(b"\0")[:-1]
        calls.append(ProverCall(b, float(t0), float(t1), int(rc), tuple(a.decode(errors="replace") for a in args)))
    return calls


def union_seconds(intervals: list[tuple[float, float]]) -> float:
    """Total length of the union of intervals (overlapping calls counted once)."""
    total, cur_s, cur_e = 0.0, None, None
    for s, e in sorted(intervals):
        if cur_e is None or s > cur_e:
            if cur_e is not None:
                total += cur_e - cur_s
            cur_s, cur_e = s, e
        else:
            cur_e = max(cur_e, e)
    if cur_e is not None:
        total += cur_e - cur_s
    return total
